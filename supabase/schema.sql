-- Testimonials: publik hanya lihat yang approved, boleh kirim dengan status pending.
drop policy if exists "Public can read approved testimonials" on public.testimonials;
create policy "Public can read approved testimonials"
  on public.testimonials for select
  using (status = 'approved');

drop policy if exists "Anyone can submit a testimonial" on public.testimonials;
create policy "Anyone can submit a testimonial"
  on public.testimonials for insert to anon, authenticated
  with check (
    status = 'pending'
    and rating between 1 and 5
    and char_length(btrim(name)) between 1 and 60
    and char_length(btrim(message)) between 1 and 500
  );

drop policy if exists "Admins manage testimonials" on public.testimonials;
create policy "Admins manage testimonials"
  on public.testimonials for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- Messages: publik hanya boleh mengirim pesan kontak, admin bebas membaca.
drop policy if exists "Anyone can send a message" on public.messages;
create policy "Anyone can send a message"
  on public.messages for insert to anon, authenticated
  with check (
    char_length(btrim(name)) between 1 and 100
    and char_length(btrim(email)) between 3 and 190
    and email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'
    and char_length(btrim(subject)) between 1 and 150
    and char_length(btrim(message)) between 1 and 3000
  );

drop policy if exists "Admins manage messages" on public.messages;
create policy "Admins manage messages"
  on public.messages for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- ============================================================
-- Batas kiriman publik (anti-spam di sisi database)
-- Honeypot di form hanya menahan bot sederhana; bot yang memanggil REST
-- API langsung tetap kena batas ini. Batasnya global per jam (bukan per
-- IP, karena Postgres tidak tahu IP pengirim). Naikkan angkanya kalau
-- terlalu ketat. Untuk proteksi lebih kuat tambahkan Turnstile/hCaptcha.
-- ============================================================

create or replace function public.limit_public_inserts()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  max_per_hour integer := tg_argv[0]::integer;
  recent integer;
begin
  execute format(
    'select count(*) from %I.%I where created_at > now() - interval ''1 hour''',
    tg_table_schema, tg_table_name
  ) into recent;

  if recent >= max_per_hour then
    raise exception 'Too many submissions right now. Please try again later.'
      using errcode = 'P0001';
  end if;
  return new;
end;
$$;

drop trigger if exists messages_rate_limit on public.messages;
create trigger messages_rate_limit
  before insert on public.messages
  for each row execute function public.limit_public_inserts(20);

drop trigger if exists testimonials_rate_limit on public.testimonials;
create trigger testimonials_rate_limit
  before insert on public.testimonials
  for each row execute function public.limit_public_inserts(10);

