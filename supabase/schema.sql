create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null,
  description text not null,
  problem text,
  solution text,
  role text,
  technologies text[] not null default '{}',
  image_url text,
  demo_url text,
  github_url text,
  sort_order integer not null default 0,
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.blogs (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null,
  excerpt text not null,
  content text not null,
  cover_url text,
  published_at date,
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.certificates (
  id bigint generated by default as identity primary key,
  title text not null,
  organizer text not null,
  description text,
  year text,
  file_url text,
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  subject text not null,
  message text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.testimonials (
  id bigint generated by default as identity primary key,
  name text not null,
  rating smallint not null default 5 check (rating between 1 and 5),
  message text not null,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

create index if not exists projects_published_idx on public.projects (is_published, id desc);
create index if not exists blogs_published_idx on public.blogs (is_published, id desc);
create index if not exists certificates_published_idx on public.certificates (is_published, id desc);
create index if not exists testimonials_status_idx on public.testimonials (status, id desc);

-- ============================================================
-- Admin allow-list
-- Hanya user yang ada di tabel ini yang dianggap admin. Tanpa ini,
-- siapa pun yang berhasil membuat akun Supabase ikut dianggap admin.
-- Tabel ini sengaja tanpa policy: tidak bisa diakses dari browser,
-- hanya lewat SQL Editor atau fungsi is_admin() di bawah.
-- ============================================================

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

